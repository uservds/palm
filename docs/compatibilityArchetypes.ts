export function getCoupleArchetype(overallScore: number): CoupleArchetype {
  const clamped = Math.max(0, Math.min(100, overallScore));
  const match = COUPLE_ARCHETYPES.find(
    (a) => clamped >= a.scoreRange[0] && (clamped < a.scoreRange[1] || clamped === 100)
  );
  return match ?? COUPLE_ARCHETYPES[0];
}