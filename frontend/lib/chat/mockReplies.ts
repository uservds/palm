function pick<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

let lastFallbackIndex = -1;

function pickFallback(): string {
  if (generalFallbacks.length === 1) return generalFallbacks[0];
  let index = Math.floor(Math.random() * generalFallbacks.length);
  while (index === lastFallbackIndex) {
    index = Math.floor(Math.random() * generalFallbacks.length);
  }
  lastFallbackIndex = index;
  return generalFallbacks[index];
}

export function generateMockReply(userText: string, category: ChatTopicCategory): string {
  if (category !== 'general') {
    return pick(repliesByCategory[category]);
  }

  const match = knowledgeBase.find((entry) => entry.keywords.test(userText));
  if (match) {
    return match.answer;
  }

  return pickFallback();
}
